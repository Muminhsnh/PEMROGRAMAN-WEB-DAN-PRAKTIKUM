// operator aritmatika 

let x = 10;
let y = 5; 
let hasil; 

// penjumlahan 
hasil = x + y;
console.log(hasil);

// pengurangan
hasil = x - y;
console.log(hasil);

// perkalian
hasil = x * y;
console.log(hasil);

// pembagian
hasil = x / y;
console.log(hasil); 

// modulus
hasil = x % y;
console.log(hasil); 

// operator logika 

// AND && => jika sama-sama bernilai true maka hasilnya true, jika salah satu bernilai false maka hasilnya false 
x = true;
y = false;

hasil= x && y;
console.log(hasil); 

// OR || => jika salah satu bernilai true maka hasilnya true, jika sama-sama bernilai false maka hasilnya false
hasil = x || y;
console.log(hasil); 

// operator perbandingan 

// sama dengan (==)
hasil = x == y;
console.log(hasil);

// tidak sama dengan (!=) 
hasil = x != y;
console.log(hasil);

// lebih besar dari (>) 
hasil = x > y;
console.log(hasil);

// lebih kecil dari (<)
hasil = x < y;
console.log(hasil);

// lebih besar dari sama dengan (>=) 
hasil = x >= y;
console.log(hasil);

// lebih kecil dari sama dengan (<=) 
hasil = x <= y;
console.log(hasil);